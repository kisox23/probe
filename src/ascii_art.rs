pub fn clear_and_render(art: &str) {
    let _ = execute!(stdout(), Clear(ClearType::All), MoveTo(0, 0));
    print!("{}", art);
}

pub fn update_ship_view(percentage: i32) -> String {
    let pct = percentage / 10;
    let mut updated = String::new();
    updated.push('[');

    let re_bar = Regex::new(r"\[[^\]]{10}\]").unwrap();

    for _ in 1..=pct {
        updated.push('=');
    }

    for _ in 0..(10 - pct) {
        updated.push(' ');
    }

    updated.push(']');

    re_bar
        .replace_all(SHIP, regex::NoExpand(updated.as_str()))
        .into_owned()
}
